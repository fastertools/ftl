var (
	// File locking to prevent race conditions
	genMutex sync.Mutex
)

func acquireFileLock(path string) (*os.File, error) {
	// Create lock file
	lockPath := path + ".lock"
	file, err := os.OpenFile(lockPath, os.O_RDWR|os.O_CREATE, 0644)
	if err != nil {
		return nil, err
	}

	// Use advisory locking
	if err := syscall.Flock(int(file.Fd()), syscall.LOCK_EX); err != nil {
		file.Close()
		return nil, err
	}

	return file, nil
}

func releaseFileLock(file *os.File) {
	if file != nil {
		syscall.Flock(int(file.Fd()), syscall.LOCK_UN)
		file.Close()
		// Remove lock file
		os.Remove(file.Name())
	}
}

func main() {
	// Prevent concurrent generation
	genMutex.Lock()
	defer genMutex.Unlock()

	log.Println("🔄 Starting CUE generation with new module structure...")

	// Load CUE files from schema directory
	ctx := cuecontext.New()

	// Load with module structure
	cfg := &load.Config{
		ModuleRoot: ".",
		Dir:        "./schema",
	}

	instances := load.Instances([]string{"."}, cfg)
	if len(instances) != 1 {
		log.Fatal("expected exactly one instance")
	}

	inst := instances[0]
	if inst.Err != nil {
		log.Fatal(inst.Err)
	}

	// Build the CUE value
	value := ctx.BuildInstance(inst)
	if value.Err() != nil {
		log.Fatal(value.Err())
	}

	// Create output directory in new location
	outputDir := "gen"
	if err := os.MkdirAll(outputDir, 0755); err != nil {
		log.Fatalf("Failed to create output directory: %v", err)
	}

	// Acquire lock for generation
	lockFile, err := acquireFileLock(filepath.Join(outputDir, ".generation"))
	if err != nil {
		log.Fatalf("Failed to acquire lock: %v", err)
	}
	defer releaseFileLock(lockFile)

	// Generate strings file
	if err := generateStringsFile(value, outputDir); err != nil {
		log.Fatal(err)
	}

	// Generate styles file
	if err := generateStylesFile(value, outputDir); err != nil {
		log.Fatal(err)
	}

	fmt.Println("✅ Generated UI constants successfully to ui/gen/")
}

func generateStringsFile(value cue.Value, outputDir string) error {
	var buf bytes.Buffer

	// Write header with new package path
	buf.WriteString(`// Code generated by ui/generate_v2.go. DO NOT EDIT.

package gen

`)

	// Process ProcessNames
	if err := generateProcessNames(&buf, value); err != nil {
		return err
	}

	// Process StatusStrings
	if err := generateStatusStrings(&buf, value); err != nil {
		return err
	}

	// Process WebUI
	if err := generateWebUI(&buf, value); err != nil {
		return err
	}

	// Process CLI
	if err := generateCLI(&buf, value); err != nil {
		return err
	}

	// Process MCP
	if err := generateMCP(&buf, value); err != nil {
		return err
	}

	// Process Handlers
	if err := generateHandlers(&buf, value); err != nil {
		return err
	}

	// Format the Go code
	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("failed to format Go code: %w", err)
	}

	// Write the file atomically
	outputFile := filepath.Join(outputDir, "strings_gen.go")
	tempFile := outputFile + ".tmp"

	if err := ioutil.WriteFile(tempFile, formatted, 0644); err != nil {
		return err
	}

	// Atomic rename
	return os.Rename(tempFile, outputFile)
}

func generateProcessNames(buf *bytes.Buffer, value cue.Value) error {
	buf.WriteString("// Process display names\n")
	buf.WriteString("const (\n")

	processNames := value.LookupPath(cue.ParsePath("#ProcessNames"))
	iter, err := processNames.Fields()
	if err != nil {
		return err
	}

	for iter.Next() {
		name := iter.Label()
		val, err := iter.Value().String()
		if err != nil {
			return err
		}
		constName := "ProcessName" + strings.Title(name)
		buf.WriteString(fmt.Sprintf("\t%s = %q\n", constName, val))
	}

	buf.WriteString(")\n\n")
	return nil
}

